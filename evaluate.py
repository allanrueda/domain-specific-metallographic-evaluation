"""
Evaluation protocol for one dataset.

Usage:

    python evaluate.py corrosion

with one of: inclusions, corrosion, boriding, h13. The images are read from

    data/<dataset>/real/            real images
    data/<dataset>/dcgan/           images generated by each GAN
    data/<dataset>/wgan-gp/
    data/<dataset>/stylegan2-ada/

and the independent unit of each real image from units/<dataset>.json.

For each of the five seeds the script

    1. splits the real images 80/20 by unit, so that all images derived
       from the same micrograph fall on the same side (same split for
       every seed)
    2. trains MaterialAE and PatchAE with early stopping on the validation
       loss, keeping the weights of the best epoch
    3. restarts a training that does not clearly improve on a predictor
       that always returns the mean training image
    4. embeds all real images and the images of each GAN
    5. computes the scores, their bootstrap distribution and the
       real vs real reference

The spread over seeds measures the variability of the learned
representation, and the bootstrap measures the finite sample uncertainty.
Results go to results/<dataset>.json and results/<dataset>_summary.txt.
"""

import copy
import json
import os
import random
import sys
import time

import numpy as np
import torch
import torch.nn.functional as F
from PIL import Image
from torch.utils.data import DataLoader, Dataset

import metrics
from models import MaterialAE, PatchAE, extract_patches


# ---------------------------------------------------------------------------
# Settings, as reported in the paper
# ---------------------------------------------------------------------------

# name: (image size, patch size, five stage autoencoders)
DATASETS = {
    "inclusions": (128, 32, False),
    "corrosion": (128, 32, False),
    "boriding": (128, 32, False),
    "h13": (256, 64, True),
}
GANS = {"dcgan": "DCGAN", "wgan-gp": "WGAN-GP", "stylegan2-ada": "StyleGAN2-ADA"}

SEEDS = [42, 1042, 2042, 3042, 4042]
MAX_EPOCHS = 300
PATIENCE = 30           # epochs without improvement before stopping
LR = 1e-3               # Adam learning rate
VAL_FRACTION = 0.2      # fraction of units used for validation
DEGENERATE = 0.65       # restart if best val MSE >= 0.65 x MSE of the mean image
MAX_ATTEMPTS = 3        # trainings per autoencoder, the best one is kept
BOOTSTRAP = 200         # bootstrap replicates
EXTENSIONS = (".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff")


# ---------------------------------------------------------------------------
# Data
# ---------------------------------------------------------------------------

def load_folder(folder, size):
    """
    Load every image of a folder, sorted by file name, as RGB.
    Returns the file names and a uint8 tensor [N, 3, size, size].
    """
    names = sorted(f for f in os.listdir(folder)
                   if f.lower().endswith(EXTENSIONS) and not f.startswith("."))
    if not names:
        sys.exit(f"no images found in {folder}")
    images = []
    for f in names:
        img = Image.open(os.path.join(folder, f)).convert("RGB")
        if img.size != (size, size):
            img = img.resize((size, size), Image.BILINEAR)
        images.append(np.asarray(img))
    return names, torch.from_numpy(np.stack(images)).permute(0, 3, 1, 2).contiguous()


class Images(Dataset):
    """
    Images kept in memory as uint8 and returned as floats in [0, 1].
    With patch = p each item is one p x p patch: item i is patch i % 16
    of image i // 16.
    """

    def __init__(self, x, patch=0):
        self.x, self.patch = x, patch

    def __len__(self):
        return len(self.x) * (16 if self.patch else 1)

    def __getitem__(self, i):
        if not self.patch:
            return self.x[i].float() / 255
        img = self.x[i // 16].float().unsqueeze(0) / 255
        return extract_patches(img, self.patch)[i % 16]


def loader(x, patch=0, batch=32, seed=None):
    """DataLoader in fixed order, or shuffled with its own generator if seed is given."""
    if seed is None:
        return DataLoader(Images(x, patch), batch_size=batch, shuffle=False)
    return DataLoader(Images(x, patch), batch_size=batch, shuffle=True,
                      generator=torch.Generator().manual_seed(seed))


# ---------------------------------------------------------------------------
# Autoencoder training
# ---------------------------------------------------------------------------

@torch.no_grad()
def val_mse(model, val, patch, device):
    """Mean squared reconstruction error on the validation images."""
    model.eval()
    total, n = 0.0, 0
    for x in val:
        x = x.to(device)
        if patch:
            x = extract_patches(x, patch)
        total += F.mse_loss(model(x), x, reduction="sum").item()
        n += x.numel()
    model.train()
    return total / n


@torch.no_grad()
def mean_image_mse(train, val, patch, device):
    """
    Validation MSE of a predictor that always returns the mean training
    image (or patch). An autoencoder that does not clearly improve on it
    has learned nothing beyond the mean, which happens when its ReLU units die.
    """
    total, n = None, 0
    for x in train:
        x = x.to(device)
        total = x.sum(0) if total is None else total + x.sum(0)
        n += len(x)
    mean = total / n
    err, m = 0.0, 0
    for x in val:
        x = x.to(device)
        if patch:
            x = extract_patches(x, patch)
        err += ((x - mean) ** 2).sum().item()
        m += x.numel()
    return err / m


def train(model, train_loader, val, patch, device):
    """Adam with early stopping. Returns the model at its best epoch."""
    opt = torch.optim.Adam(model.parameters(), LR)
    model.to(device).train()
    history = []                          # (train MSE, val MSE) per epoch
    best, best_state, wait = np.inf, None, 0
    for epoch in range(MAX_EPOCHS):
        total, batches = 0.0, 0
        for x in train_loader:
            x = x.to(device)
            loss = F.mse_loss(model(x), x)
            opt.zero_grad()
            loss.backward()
            opt.step()
            total += loss.item()
            batches += 1
        history.append((total / batches, val_mse(model, val, patch, device)))
        if history[-1][1] < best - 1e-7:
            best, wait = history[-1][1], 0
            best_state = copy.deepcopy(model.state_dict())
            model.best_epoch = epoch + 1
        else:
            wait += 1
            if wait >= PATIENCE:
                break
    model.load_state_dict(best_state)
    return model, history


def fit(build, train_loader, train_fixed, val, patch, seed, device):
    """
    Train an autoencoder and check that the training is not degenerate.

    r = best val MSE / val MSE of the mean image. If r >= DEGENERATE the
    training is repeated with another initialization, up to MAX_ATTEMPTS,
    and the attempt with the lowest r is kept.
    """
    state = torch.get_rng_state()       # computing the baseline must not change the
    baseline = mean_image_mse(train_fixed, val, patch, device)
    torch.set_rng_state(state)          # initialization of the first attempt
    best, attempts = None, 0
    for attempt in range(MAX_ATTEMPTS):
        attempts += 1
        if attempt > 0:
            torch.manual_seed(seed + 100000 * attempt)
        t0 = time.time()
        model, history = train(build().to(device), train_loader, val, patch, device)
        r = min(h[1] for h in history) / baseline
        info = {"r": r, "best_epoch": model.best_epoch,
                "history": history, "train_time_s": time.time() - t0}
        if best is None or r < best[1]["r"]:
            best = (model, info)
        if r < DEGENERATE:
            break
    model, info = best
    info["restarts"] = attempts - 1
    return model, info


@torch.no_grad()
def embed(model, x, patch, device):
    """Embeddings [N, 256] for MaterialAE, or [N, 16, 128] for PatchAE."""
    model.eval()
    out = []
    for b in loader(x):
        b = b.to(device)
        if patch:
            z = model.encode(extract_patches(b, patch)).view(len(b), 16, -1)
        else:
            z = model.encode(b)
        out.append(z.cpu().numpy())
    return np.concatenate(out).astype(np.float64)


# ---------------------------------------------------------------------------
# Protocol
# ---------------------------------------------------------------------------

def main(dataset):
    size, patch, deep = DATASETS[dataset]
    root = os.path.join("data", dataset)
    device = ("cuda" if torch.cuda.is_available() else
              "mps" if torch.backends.mps.is_available() else "cpu")
    if device == "cuda":
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
    print(f"{dataset} on {device}")

    # Real images and their independent units
    names, real = load_folder(os.path.join(root, "real"), size)
    unit_of = json.load(open(os.path.join("units", f"{dataset}.json"), encoding="utf-8"))
    missing = [n for n in names if n not in unit_of]
    if missing:
        sys.exit(f"{len(missing)} images without unit in units/{dataset}.json, e.g. {missing[0]}")
    units = np.array([unit_of[n] for n in names])
    fakes = {GANS[g]: load_folder(os.path.join(root, g), size)[1] for g in GANS}

    # 80/20 split by unit, fixed for all seeds
    u = np.random.default_rng(0).permutation(np.unique(units))
    val_units = set(u[: int(round(VAL_FRACTION * len(u)))].tolist())
    is_val = np.array([q in val_units for q in units])
    x_train, x_val = real[~is_val], real[is_val]
    print(f"{len(real)} real images, {len(u)} units, train/val = {len(x_train)}/{len(x_val)}")

    results = {"dataset": dataset, "n_images": len(real), "n_units": len(u),
               "n_train": len(x_train), "n_val": len(x_val), "device": device, "seeds": {}}
    for seed in SEEDS:
        print(f"seed {seed}")
        random.seed(seed)
        np.random.seed(seed)
        torch.manual_seed(seed)
        if device == "cuda":
            torch.cuda.reset_peak_memory_stats()

        # Train both autoencoders on the training units only
        g_model, g_info = fit(lambda: MaterialAE(deep), loader(x_train, seed=seed),
                              loader(x_train), loader(x_val), 0, seed, device)
        l_model, l_info = fit(lambda: PatchAE(deep), loader(x_train, patch, 64, seed),
                              loader(x_train, patch, 64), loader(x_val), patch, seed, device)
        for name, info in (("MaterialAE", g_info), ("PatchAE", l_info)):
            print(f"  {name}: best epoch {info['best_epoch']}, r = {info['r']:.2f}, "
                  f"restarts {info['restarts']}")

        # Real embeddings, scale of each space and kernel bandwidths
        R, Rl = embed(g_model, real, 0, device), embed(l_model, real, patch, device)
        rl = Rl.reshape(-1, Rl.shape[-1])
        tr = {"g": float(np.trace(metrics.covariance(R))), "l": float(np.trace(metrics.covariance(rl)))}
        sig = {"g": metrics.median_sigma(R, seed=seed), "l": metrics.median_sigma(rl, seed=seed)}

        S = {"MaterialAE": g_info, "PatchAE": l_info,
             "params": {"MaterialAE": sum(p.numel() for p in g_model.parameters()),
                        "PatchAE": sum(p.numel() for p in l_model.parameters())},
             "reference": metrics.reference(R, Rl, units, tr, seed), "models": {}}

        # Scores of each generator
        for gan, x in fakes.items():
            G, Gl = embed(g_model, x, 0, device), embed(l_model, x, patch, device)
            S["models"][gan] = {
                "scores": metrics.scores(R, G, Rl, Gl, units, sig, tr, seed=seed),
                "half": metrics.half_vs_generated(R, G, Rl, Gl, units, tr, seed),
                "boot": {k: v.tolist() for k, v in
                         metrics.bootstrap(R, G, Rl, Gl, units, sig, tr, BOOTSTRAP, seed=seed).items()},
            }
        if device == "cuda":
            S["peak_memory_MB"] = torch.cuda.max_memory_allocated() / 2 ** 20
        results["seeds"][seed] = S

    os.makedirs("results", exist_ok=True)
    with open(os.path.join("results", f"{dataset}.json"), "w", encoding="utf-8") as f:
        json.dump(results, f)
    text = summary(results)
    with open(os.path.join("results", f"{dataset}_summary.txt"), "w", encoding="utf-8") as f:
        f.write(text)
    print(text)


# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------

def summary(res):
    """Text with the values reported in the tables of the paper."""
    S = list(res["seeds"].values())
    gans = list(S[0]["models"])
    keys = ["nFID_g", "nFID_l", "MMD2_g", "MMD2_l"]
    point = lambda g, k: np.array([s["models"][g]["scores"][k] for s in S])
    boot = lambda g, k: np.concatenate([s["models"][g]["boot"][k] for s in S])
    L = [f"{res['dataset']}: {res['n_images']} images, {res['n_units']} units, "
         f"train/val {res['n_train']}/{res['n_val']}, {len(S)} seeds", ""]

    # Mean over seeds, std over seeds (representation) and bootstrap std (sampling)
    L.append("Scores: mean, std over autoencoder trainings, (bootstrap std)")
    for g in gans:
        cells = []
        for k in keys:
            b = np.mean([np.std(s["models"][g]["boot"][k], ddof=1) for s in S])
            cells.append(f"{k} {point(g, k).mean():.3f} {point(g, k).std(ddof=1):.3f} ({b:.3f})")
        L.append(f"  {g:<14} " + "   ".join(cells))
    ref = {c: np.mean([s["reference"][c] for s in S]) for c in "gl"}
    L.append(f"  {'Reference':<14} nFID_g {ref['g']:.3f}   nFID_l {ref['l']:.3f}")

    # Best model per training, and probability of ranking first over bootstrap replicates
    L += ["", "Ranking: trainings won, (bootstrap probability of ranking first)"]
    for k in keys + ["KID_g", "MMD2_g_sigma_x0.5", "MMD2_g_sigma_x2.0"]:
        wins = [min(gans, key=lambda g: s["models"][g]["scores"][k]) for s in S]
        cells = [f"{g} {wins.count(g)}/{len(S)}" for g in gans]
        if k in keys:
            first = np.argmin(np.array([boot(g, k) for g in gans]), 0)
            cells = [f"{c} ({np.mean(first == i):.2f})" for i, c in enumerate(cells)]
        L.append(f"  {k:<18} " + "   ".join(cells))

    # Ratio to the real vs real reference at the same sample size
    L += ["", "Calibration: nFID at half size / reference (about 1 or less = like real data)"]
    for g in gans:
        h = {c: np.mean([s["models"][g]["half"][c] for s in S]) for c in "gl"}
        L.append(f"  {g:<14} global {h['g'] / ref['g']:.2f}   local {h['l'] / ref['l']:.2f}")

    L += ["", "Precision and recall, mean over trainings"]
    for g in gans:
        L.append(f"  {g:<14} " + "   ".join(f"{k} {point(g, k).mean():.2f}"
                                            for k in ["P_g", "R_g", "P_l", "R_l"]))

    L += ["", "Autoencoders: best epochs, highest r (< 0.65 is valid), restarts, "
              "parameters, mean training time"]
    for a in ["MaterialAE", "PatchAE"]:
        ep = [s[a]["best_epoch"] for s in S]
        L.append(f"  {a:<10} epochs {min(ep)}-{max(ep)}   r {max(s[a]['r'] for s in S):.2f}   "
                 f"restarts {sum(s[a]['restarts'] for s in S)}   params {S[0]['params'][a]:,}   "
                 f"time {np.mean([s[a]['train_time_s'] for s in S]):.0f} s")
    if "peak_memory_MB" in S[0]:
        L.append(f"  peak GPU memory {max(s['peak_memory_MB'] for s in S):.0f} MB")
    return "\n".join(L)


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in DATASETS:
        sys.exit("usage: python evaluate.py <" + "|".join(DATASETS) + ">")
    main(sys.argv[1])
